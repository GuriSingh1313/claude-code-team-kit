#!/usr/bin/env node
// Claude Code readiness audit.
//
//   node .claude/tools/claude-ready.mjs [path] [--json] [--out report.md] [--min-score 80]
//
// Scores a repository 0-100 on how safely and productively an AI coding agent can
// work in it, and lists the fixes in priority order. --min-score makes it a CI gate.
import { writeFileSync } from "node:fs";
import { resolve, basename } from "node:path";
import { runChecks, score, AREAS } from "./checks.mjs";
import { isMain } from "../hooks/lib.mjs";

const ICON = { pass: "✅", warn: "⚠️", fail: "❌", na: "➖" };

export function audit(dir) {
  const target = resolve(dir);
  const { facts, results } = runChecks(target);
  return { target, project: facts.project, results, score: score(results) };
}

export function renderMarkdown(report, { date = new Date().toISOString().slice(0, 10) } = {}) {
  const { project, results, score: s } = report;
  const lines = [];
  lines.push(`# Claude Code Readiness Report: ${project.name || basename(report.target)}`);
  lines.push("");
  lines.push(`**Score: ${s.value}/100 (grade ${s.grade})** · Stack: ${project.stacks.join(", ") || "not detected"} · Scanned ${date}`);
  lines.push("");
  lines.push("| Area | Score |");
  lines.push("|---|---|");
  for (const [key, label] of Object.entries(AREAS)) {
    const a = s.byArea[key];
    if (a) lines.push(`| ${label} | ${a.got}/${a.max} |`);
  }
  lines.push("");
  lines.push("## Checks");
  lines.push("");
  lines.push("| | Check | Points | Details |");
  lines.push("|---|---|---|---|");
  for (const r of results) {
    const pts = r.status === "na" ? "n/a" : `${r.points}/${r.max}`;
    lines.push(`| ${ICON[r.status]} | ${r.title} | ${pts} | ${String(r.detail).replace(/\|/g, "\\|")} |`);
  }
  const todo = results.filter((r) => r.status === "fail" || r.status === "warn").sort((a, b) => b.max - b.points - (a.max - a.points));
  lines.push("");
  if (todo.length) {
    lines.push("## Fix these first");
    lines.push("");
    todo.forEach((r, i) => lines.push(`${i + 1}. **${r.title}** (+${r.max - r.points} pts): ${r.fix}`));
  } else {
    lines.push("## Nothing to fix");
    lines.push("");
    lines.push("Every check passes. Re-run this audit in CI with `--min-score` to keep it that way.");
  }
  lines.push("");
  lines.push("---");
  lines.push("*Generated by the claude-code-team-kit readiness audit · `node .claude/tools/claude-ready.mjs`*");
  return lines.join("\n");
}

function parseArgs(argv) {
  const opts = { path: ".", json: false, out: null, minScore: null };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--json") opts.json = true;
    else if (a === "--out") opts.out = argv[++i];
    else if (a === "--min-score") opts.minScore = Number(argv[++i]);
    else if (a === "-h" || a === "--help") opts.help = true;
    else opts.path = a;
  }
  return opts;
}

if (isMain(import.meta.url)) {
  const opts = parseArgs(process.argv.slice(2));
  if (opts.help) {
    console.log("Usage: node .claude/tools/claude-ready.mjs [path] [--json] [--out report.md] [--min-score N]");
    process.exit(0);
  }
  const report = audit(opts.path);
  const output = opts.json ? JSON.stringify(report, null, 2) : renderMarkdown(report);
  if (opts.out) {
    writeFileSync(opts.out, `${output}\n`);
    console.log(`Readiness score ${report.score.value}/100 (${report.score.grade}). Report written to ${opts.out}`);
  } else {
    console.log(output);
  }
  if (opts.minScore != null && report.score.value < opts.minScore) {
    console.error(`Readiness score ${report.score.value} is below the required ${opts.minScore}.`);
    process.exit(1);
  }
}
